// @ts-check
'use strict';
/**
 * Claude Code transcripts (<config>/projects/<dir>/<sessionId>.jsonl) → ActivityEntry lines (contract v3).
 * Used for outside sessions (external.js): no hooks reach us from those, so their transcript is the record.
 *
 * Pure parsing (parseLine) plus a small incremental reader (TranscriptTail) that reads only new bytes and
 * leaves a half-written last line for the next read. Real transcripts hold many line types besides
 * user / assistant (summary, system, attachment, file-history-snapshot, progress, ...): those are skipped.
 * Never stores tool responses or file contents: only tool names, a one-line detail, timings and errors.
 */
const fs = require('fs');
const path = require('path');
const { summarizeTool } = require('./status');

const MAX_DETAIL = 300;
const MAX_TEXT = 500;
/** A first read of a huge transcript starts this many bytes before its end. */
const MAX_FIRST_READ = 8 * 1024 * 1024;
/** One read() takes at most this much (the rest comes next time). */
const MAX_READ = 4 * 1024 * 1024;
const AGENT_TOOLS = new Set(['Agent', 'Task']);

/**
 * @typedef {import('./types').ActivityEntry} ActivityEntry
 * @typedef {Omit<ActivityEntry, 'seq'>} RawEntry
 * @typedef {{
 *   pending: Map<string, {tool: string, detail: string, at: number}>,
 *   agentCalls: Map<string, {description: string, type: string, background: boolean}>,
 *   agentIds: Map<string, string>,
 *   notifications: Array<{taskId: string, toolUseId: string, status: string, summary: string, at: number}>,
 *   lastText: string,
 *   lastTool: {tool: string, detail: string}|null,
 *   lastPrompt: string,
 *   tools: number,
 *   errors: number,
 * }} ParseState
 */

/** @returns {ParseState} */
function newParseState() {
  return { pending: new Map(), agentCalls: new Map(), agentIds: new Map(), notifications: [], lastText: '', lastTool: null, lastPrompt: '', tools: 0, errors: 0 };
}

/** The folder name Claude Code uses under projects/ for a cwd: every non-alphanumeric character becomes '-'. */
function projectDirName(cwd) {
  return String(cwd || '').replace(/[^a-zA-Z0-9]/g, '-');
}

/**
 * Find a session's transcript: Claude's folder for cwd first, then every project folder.
 * @param {string} configDir @param {string} cwd @param {string} sessionId @param {{scan?: boolean}} [opts]
 * @returns {string} '' when not found
 */
function findTranscript(configDir, cwd, sessionId, opts = {}) {
  if (!/^[\w.-]+$/.test(sessionId)) return '';
  const projects = path.join(configDir, 'projects');
  const direct = path.join(projects, projectDirName(cwd), `${sessionId}.jsonl`);
  if (isFile(direct)) return direct;
  if (opts.scan === false) return '';
  let dirs = [];
  try { dirs = fs.readdirSync(projects, { withFileTypes: true }); } catch { return ''; }
  for (const d of dirs) {
    if (!d.isDirectory()) continue;
    const f = path.join(projects, d.name, `${sessionId}.jsonl`);
    if (isFile(f)) return f;
  }
  return '';
}

function isFile(f) {
  try { return fs.statSync(f).isFile(); } catch { return false; }
}

/** Collapse whitespace and cap. @param {string} s @param {number} max */
function oneLine(s, max) {
  return String(s || '').split(/\s+/).filter(Boolean).join(' ').slice(0, max);
}

/** @param {string} s @param {number} max */
function capText(s, max) {
  return String(s || '').trim().slice(0, max);
}

/** @param {string} text @param {string} tag */
function tagValue(text, tag) {
  const m = new RegExp(`<${tag}>([\\s\\S]*?)</${tag}>`).exec(text);
  return m ? m[1].trim() : '';
}

/**
 * What the user typed, or null for lines that are not the user typing (reminders, command output, ...).
 * @param {string} text @returns {{kind: 'prompt'|'notice', text: string}|null}
 */
function userText(text) {
  const t = String(text || '').trim();
  if (!t) return null;
  if (t.startsWith('<command-name>') || t.includes('<command-name>')) {
    const name = tagValue(t, 'command-name');
    const args = tagValue(t, 'command-args');
    return name ? { kind: 'prompt', text: capText(args ? `${name} ${args}` : name, MAX_TEXT) } : null;
  }
  if (t.startsWith('<bash-input>')) return { kind: 'prompt', text: capText(`!${tagValue(t, 'bash-input')}`, MAX_TEXT) };
  if (/^\[Request interrupted by user/.test(t)) return { kind: 'notice', text: 'Interrupted by the user' };
  // <system-reminder>, <local-command-stdout>, <bash-stdout>, <user-memory-input> ... : not a prompt.
  if (/^<[\w-]+>/.test(t)) return null;
  if (t.startsWith('Caveat: The messages below were generated by the user while running local commands')) return null;
  return { kind: 'prompt', text: capText(t, MAX_TEXT) };
}

/** @param {any} content @returns {string} text blocks joined */
function textOf(content) {
  if (typeof content === 'string') return content;
  if (!Array.isArray(content)) return '';
  return content.filter((b) => b && b.type === 'text' && typeof b.text === 'string').map((b) => b.text).join('\n');
}

/** @param {any} obj @param {number} fallback */
function timeOf(obj, fallback) {
  const t = typeof obj.timestamp === 'string' ? Date.parse(obj.timestamp) : NaN;
  return Number.isFinite(t) ? t : fallback;
}

/**
 * One parsed transcript line → activity entries (without seq). Updates st (pending tools, Agent calls,
 * task notifications, last prompt / text / tool, counts). Unknown or malformed lines give [].
 * @param {any} obj @param {ParseState} st @param {{subagentId?: string, now?: number}} [opts]
 * @returns {RawEntry[]}
 */
function parseLine(obj, st, opts = {}) {
  if (!obj || typeof obj !== 'object' || (obj.type !== 'user' && obj.type !== 'assistant')) return [];
  const msg = obj.message;
  if (!msg || typeof msg !== 'object') return [];
  const subagentId = opts.subagentId || '';
  // Older Claude versions wrote subagent lines into the main file: keep them apart (or skip them).
  if (!subagentId && obj.isSidechain === true) return [];
  const at = timeOf(obj, opts.now || Date.now());
  /** @type {RawEntry[]} */
  const out = [];
  const content = msg.content;

  if (obj.type === 'assistant') {
    if (!Array.isArray(content)) return [];
    for (const b of content) {
      if (!b || typeof b !== 'object') continue;
      if (b.type === 'tool_use' && typeof b.name === 'string') {
        const tool = b.name;
        const input = b.input && typeof b.input === 'object' ? b.input : {};
        const detail = oneLine(summarizeTool(tool, input), MAX_DETAIL);
        if (typeof b.id === 'string') st.pending.set(b.id, { tool, detail, at });
        if (AGENT_TOOLS.has(tool) && typeof b.id === 'string') {
          st.agentCalls.set(b.id, {
            description: oneLine(typeof input.description === 'string' ? input.description : '', MAX_TEXT),
            type: typeof input.subagent_type === 'string' ? input.subagent_type : '',
            background: input.run_in_background === true,
          });
        }
        st.lastTool = { tool, detail };
        st.tools += 1;
        /** @type {RawEntry} */
        const e = { at, subagentId, kind: 'tool', tool };
        if (detail) e.detail = detail;
        out.push(e);
      } else if (b.type === 'text' && typeof b.text === 'string' && b.text.trim()) {
        st.lastText = capText(b.text, MAX_TEXT);
      }
    }
    return out;
  }

  // user
  if (obj.isMeta === true) return [];
  if (typeof content === 'string') {
    if (subagentId) return []; // a subagent's "prompt" is its task from the parent, not the user
    const t = content.trim();
    if (t.startsWith('<task-notification>')) {
      const n = {
        taskId: tagValue(t, 'task-id'), toolUseId: tagValue(t, 'tool-use-id'),
        status: tagValue(t, 'status'), summary: oneLine(tagValue(t, 'summary'), MAX_TEXT), at,
      };
      st.notifications.push(n);
      const call = st.agentCalls.get(n.toolUseId);
      const m = /^Agent "([\s\S]*)" (finished|failed|completed|was stopped|stopped)/.exec(n.summary);
      const title = (call && call.description) || (m && m[1]) || n.summary || 'subagent';
      const failed = /fail|error/i.test(n.status);
      out.push({ at, subagentId: '', kind: 'notice', text: capText(`Subagent ${failed ? 'failed' : 'finished'}: ${title}`, MAX_TEXT) });
      return out;
    }
    const u = userText(t);
    if (!u) return [];
    if (u.kind === 'prompt') st.lastPrompt = u.text;
    out.push({ at, subagentId, kind: u.kind, text: u.text });
    return out;
  }
  if (!Array.isArray(content)) return [];
  const tur = obj.toolUseResult && typeof obj.toolUseResult === 'object' ? obj.toolUseResult : null;
  for (const b of content) {
    if (!b || typeof b !== 'object') continue;
    if (b.type === 'tool_result' && typeof b.tool_use_id === 'string') {
      const p = st.pending.get(b.tool_use_id);
      st.pending.delete(b.tool_use_id);
      if (tur && typeof tur.agentId === 'string' && /^[\w-]+$/.test(tur.agentId)) st.agentIds.set(b.tool_use_id, tur.agentId);
      const err = b.is_error === true;
      if (err) st.errors += 1;
      /** @type {RawEntry} */
      const e = { at, subagentId, kind: err ? 'tool_error' : 'tool_done', tool: p ? p.tool : '' };
      if (p && p.detail) e.detail = p.detail;
      if (p) e.ms = Math.max(0, at - p.at);
      out.push(e);
    } else if (b.type === 'text' && typeof b.text === 'string' && !subagentId) {
      const u = userText(b.text);
      if (!u) continue;
      if (u.kind === 'prompt') st.lastPrompt = u.text;
      out.push({ at, subagentId, kind: u.kind, text: u.text });
    }
  }
  return out;
}

/** Split text into JSON objects, one per line; bad lines are skipped. @param {string} text @returns {any[]} */
function parseJsonLines(text) {
  const out = [];
  for (const line of text.split('\n')) {
    const l = line.trim();
    if (!l) continue;
    try { out.push(JSON.parse(l)); } catch { /* not JSON (or cut): skip */ }
  }
  return out;
}

/**
 * Reads a growing JSONL file from where it left off. Only whole lines (ending in \n) are returned; a
 * half-written last line stays for the next read. If the file shrinks (rewritten), it starts over and
 * read() reports reset: true.
 */
class TranscriptTail {
  /** @param {string} file @param {{maxFirstRead?: number, maxRead?: number}} [opts] */
  constructor(file, opts = {}) {
    this.file = file;
    this.offset = 0;
    this.started = false;
    this.maxFirstRead = opts.maxFirstRead || MAX_FIRST_READ;
    this.maxRead = opts.maxRead || MAX_READ;
    /** skip bytes up to the first newline (we started in the middle of a line) */
    this.skipPartial = false;
  }

  /** @returns {{lines: any[], reset: boolean}} */
  read() {
    let fd;
    try { fd = fs.openSync(this.file, 'r'); } catch { return { lines: [], reset: false }; }
    try {
      const size = fs.fstatSync(fd).size;
      let reset = false;
      if (!this.started) {
        this.started = true;
        if (size > this.maxFirstRead) { this.offset = size - this.maxFirstRead; this.skipPartial = true; }
      } else if (size < this.offset) {
        this.offset = 0;
        this.skipPartial = false;
        reset = true;
      }
      if (size <= this.offset) return { lines: [], reset };
      const len = Math.min(size - this.offset, this.maxRead);
      const buf = Buffer.alloc(len);
      const n = fs.readSync(fd, buf, 0, len, this.offset);
      let start = 0;
      if (this.skipPartial) {
        const nl = buf.indexOf(0x0a);
        if (nl < 0 || nl >= n) { this.offset += n; return { lines: [], reset }; }
        start = nl + 1;
        this.skipPartial = false;
      }
      const last = buf.lastIndexOf(0x0a, n - 1);
      if (last < start) {
        // No whole line yet. A single line longer than maxRead: drop it rather than stall forever.
        if (n === this.maxRead && start === 0) { this.offset += n; this.skipPartial = true; }
        else this.offset += start;
        return { lines: [], reset };
      }
      this.offset += last + 1;
      return { lines: parseJsonLines(buf.subarray(start, last + 1).toString('utf8')), reset };
    } finally {
      try { fs.closeSync(fd); } catch { /* ignore */ }
    }
  }
}

/**
 * A subagent's meta file (<sessionId>/subagents/agent-<id>.meta.json), read defensively.
 * @param {any} meta
 * @returns {{type: string, description: string, toolUseId: string, background: boolean, finished: boolean}|null}
 */
function parseMeta(meta) {
  if (!meta || typeof meta !== 'object' || Array.isArray(meta)) return null;
  return {
    type: typeof meta.agentType === 'string' ? meta.agentType : '',
    description: typeof meta.description === 'string' ? oneLine(meta.description, MAX_TEXT) : '',
    toolUseId: typeof meta.toolUseId === 'string' ? meta.toolUseId : '',
    background: meta.requestShape === 'background',
    finished: meta.finished === true,
  };
}

module.exports = {
  MAX_DETAIL, MAX_TEXT, AGENT_TOOLS,
  newParseState, projectDirName, findTranscript, parseLine, parseJsonLines, userText, parseMeta, TranscriptTail,
};
